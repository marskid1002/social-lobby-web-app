// Helper: get user by id, with safe fallback.
export function getUser(id: string): User | undefined {
  return users.find((u) => u.id === id);
}

// Helper: get online status for a user, if currently online.
export function getOnlineStatus(userId: string): OnlineStatus | undefined {
  return onlineStatuses.find((s) => s.userId === userId);
}

// Helper: who's currently "online" (has a status row)?
export function getOnlineUserIds(): string[] {
  return onlineStatuses.map((s) => s.userId);
}
